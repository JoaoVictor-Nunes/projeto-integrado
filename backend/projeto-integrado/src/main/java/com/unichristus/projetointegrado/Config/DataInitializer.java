package com.unichristus.projetointegrado.Config;

import com.unichristus.projetointegrado.domain.model.Disciplina;
import com.unichristus.projetointegrado.domain.model.TipoPerfil;
import com.unichristus.projetointegrado.domain.model.User;
import com.unichristus.projetointegrado.repository.DisciplinaRepository;
import com.unichristus.projetointegrado.repository.UserRepository;
import org.springframework.boot.CommandLineRunner;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.security.crypto.password.PasswordEncoder;

import java.time.LocalDateTime;
import java.util.Map;

@Configuration
public class DataInitializer {

    @Bean
    public CommandLineRunner seedUsers(UserRepository userRepository, PasswordEncoder passwordEncoder) {
        return args -> {
            // 1. Criar Administrador
            if (!userRepository.existsByEmail("admin@sibv.com")) {
                User admin = new User();
                admin.setNome("Administrador SIBV");
                admin.setEmail("admin@sibv.com");
                admin.setMatricula("ADM0001");
                admin.setSenhaHash(passwordEncoder.encode("Admin123")); // campo senha_hash
                admin.setPerfil(TipoPerfil.ADMIN);
                admin.setStatusAtivo(true);                             // campo status_ativo
                admin.setDataCriacao(LocalDateTime.now());              // campo data_criacao (NOT NULL)

                userRepository.save(admin);
                System.out.println(">>> Usuário admin@sibv.com criado com sucesso!");
            }

            // 2. Criar Professor / Usuário Padrão
            if (!userRepository.existsByEmail("professor@sibv.com")) {
                User professor = new User();
                professor.setNome("Professor Teste");
                professor.setEmail("professor@sibv.com");
                professor.setMatricula("PROF0001");
                professor.setSenhaHash(passwordEncoder.encode("Professor123"));
                professor.setPerfil(TipoPerfil.ALUNO); 
                professor.setStatusAtivo(true);
                professor.setDataCriacao(LocalDateTime.now());

                userRepository.save(professor);
                System.out.println(">>> Usuário professor@sibv.com criado com sucesso!");
            }
        };
    }

    /** Disciplinas iniciais. Só cria as que ainda não existem (pelo nome). */
    @Bean
    public CommandLineRunner seedDisciplinas(DisciplinaRepository disciplinaRepository, JdbcTemplate jdbcTemplate) {
        return args -> {
            corrigirIdDisciplinas(jdbcTemplate);

            Map<String, String> disciplinas = Map.of(
                    "Geografia", "Espaço geográfico, paisagens, territórios, clima e relações entre sociedade e natureza.",
                    "História", "Estudo das sociedades humanas ao longo do tempo, seus processos, culturas e transformações.",
                    "Matemática", "Números, álgebra, geometria, estatística e raciocínio lógico.");

            disciplinas.forEach((nome, descricao) -> {
                if (!disciplinaRepository.existsByNomeIgnoreCase(nome)) {
                    Disciplina disciplina = new Disciplina();
                    disciplina.setNome(nome);
                    disciplina.setDescricao(descricao);
                    disciplinaRepository.save(disciplina);
                    System.out.println(">>> Disciplina " + nome + " criada com sucesso!");
                }
            });
        };
    }

    /**
     * Bancos criados antes do @GeneratedValue(IDENTITY) em Disciplina ficaram
     * com tb_categorias.id sem auto incremento (o ddl-auto=update não altera
     * colunas existentes), e todo INSERT falha com "id nulo". Aqui a coluna
     * vira IDENTITY, começando depois do maior id que já existir. Em bancos
     * já corretos, não faz nada.
     */
    private void corrigirIdDisciplinas(JdbcTemplate jdbcTemplate) {
        jdbcTemplate.execute("""
                DO $$
                BEGIN
                    IF EXISTS (
                        SELECT 1 FROM information_schema.columns
                        WHERE table_schema = current_schema()
                          AND table_name = 'tb_categorias'
                          AND column_name = 'id'
                          AND is_identity = 'NO'
                          AND column_default IS NULL
                    ) THEN
                        ALTER TABLE tb_categorias ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
                        PERFORM setval(pg_get_serial_sequence('tb_categorias', 'id'),
                                       COALESCE((SELECT MAX(id) FROM tb_categorias), 0) + 1, false);
                    END IF;
                END $$;
                """);
    }
}
